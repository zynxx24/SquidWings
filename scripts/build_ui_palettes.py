"""Write the web UI's colour palettes into web/static/css/tokens.css (between the palettes markers).

Every palette is built in OKLCH with the design genome's helpers (tools/toolbox/design_genome.py) and
pushed until it passes WCAG: body text 7:1 or more on the page, secondary text and accent text 4.5:1 or more on every
surface they sit on, the accent's ink 4.5:1 on the accent. The neutrals carry a trace of the accent's hue so each
palette feels like one piece. A failed check stops the script instead of writing a palette that is hard to read.

    .venv/bin/python scripts/build_ui_palettes.py          # rewrite the block in tokens.css
    .venv/bin/python scripts/build_ui_palettes.py --check  # print the contrast table only

Add a palette by adding a line to PALETTES; the pickers in the chat and trading pages read their list from
``--palette-list`` in the generated CSS, so nothing else needs to change.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools.toolbox.design_genome import contrast, oklch_hex  # noqa: E402

TOKENS = ROOT / "web" / "static" / "css" / "tokens.css"
START, END = "/* palettes:start (generated by scripts/build_ui_palettes.py) */", "/* palettes:end */"

# id, label, accent hue, accent chroma, neutral chroma, hue of the second chart series. The first one is the default.
# The second series hue was picked with the dataviz validator (validate_palette.js): it must stay apart from the
# first under deuteranopia/protanopia (ΔE >= 8), which the plain opposite hue does not for teal, green and pink.
PALETTES: list[tuple[str, str, float, float, float, float]] = [
    ("laut", "Laut", 182, 0.105, 0.007, 75),
    ("samudra", "Samudra", 242, 0.13, 0.009, 62),
    ("zamrud", "Zamrud", 152, 0.13, 0.008, 260),
    ("kunyit", "Kunyit", 78, 0.13, 0.010, 258),
    ("bata", "Bata", 38, 0.14, 0.010, 218),
    ("anggrek", "Anggrek", 350, 0.15, 0.009, 75),
    ("grafit", "Grafit", 250, 0.025, 0.004, 70),
]

# Semantic hues stay put across palettes, so "up", "down" and "careful" always read the same.
OK_H, WARN_H, ERR_H, INFO_H = 150, 68, 27, 245


def reach(target: float, against: list[str], lightness: float, chroma: float, hue: float, darker: bool) -> str:
    """Move lightness toward black (or white) until the colour reaches the ratio on every background."""
    step = -0.005 if darker else 0.005
    value = lightness
    colour = oklch_hex(value, chroma, hue)
    while min(contrast(colour, bg) for bg in against) < target and 0.0 < value < 1.0:
        value = min(1.0, max(0.0, value + step))
        colour = oklch_hex(value, chroma, hue)
    return colour


def ink_for(colour: str, hue: float, dark_ink_l: float = 0.18) -> str:
    """White or a deep shade of the hue, whichever reads better on ``colour``."""
    deep = oklch_hex(dark_ink_l, 0.04, hue)
    return "#FFFFFF" if contrast("#FFFFFF", colour) >= contrast(deep, colour) else deep


def light(h: float, c: float, n: float, h2: float) -> dict[str, str]:
    p = {
        "bg": oklch_hex(0.975, n, h),
        "surface": oklch_hex(0.997, n * 0.35, h),
        "surface-2": oklch_hex(0.952, n * 1.1, h),
        "surface-3": oklch_hex(0.925, n * 1.3, h),
        "line": oklch_hex(0.905, n * 1.2, h),
        "line-strong": oklch_hex(0.835, n * 1.4, h),
        "user": oklch_hex(0.935, n * 1.8, h),
        "text": oklch_hex(0.215, n * 1.6, h),
    }
    bgs = [p["bg"], p["surface"], p["surface-2"]]
    p["muted"] = reach(5.6, bgs, 0.50, n * 2, h, darker=True)
    p["faint"] = reach(4.5, bgs, 0.58, n * 2, h, darker=True)
    p["accent"] = reach(4.8, bgs + [oklch_hex(0.94, c * 0.28, h)], 0.56, c, h, darker=True)
    p["accent-hover"] = reach(contrast(p["accent"], p["surface"]) + 1.1, [p["surface"]], 0.5, c, h, darker=True)
    p["accent-ink"] = ink_for(p["accent"], h)
    p["accent-soft"] = oklch_hex(0.945, c * 0.28, h)
    p["accent-line"] = oklch_hex(0.86, c * 0.5, h)
    for name, hue in (("ok", OK_H), ("warn", WARN_H), ("err", ERR_H), ("info", INFO_H)):
        soft = oklch_hex(0.952, 0.035, hue)
        p[f"{name}-soft"] = soft
        p[name] = reach(4.6, bgs + [soft], 0.55, 0.15, hue, darker=True)
    p["focus"] = p["accent"]
    p["chart-1"] = reach(3.2, [p["surface"]], 0.6, max(c, 0.13), h, darker=True)   # charts want more colour than text
    p["chart-2"] = reach(3.2, [p["surface"]], 0.62, 0.13, h2, darker=True)
    p["chart-3"] = reach(3.2, [p["surface"]], 0.66, 0.14, (h + 90) % 360, darker=True)
    p["chart-4"] = p["faint"]
    return p


def dark(h: float, c: float, n: float, h2: float) -> dict[str, str]:
    p = {
        "bg": oklch_hex(0.165, n * 1.4, h),
        "surface": oklch_hex(0.198, n * 1.5, h),
        "surface-2": oklch_hex(0.238, n * 1.6, h),
        "surface-3": oklch_hex(0.272, n * 1.7, h),
        "line": oklch_hex(0.290, n * 1.7, h),
        "line-strong": oklch_hex(0.375, n * 1.8, h),
        "user": oklch_hex(0.262, n * 2.2, h),
        "text": oklch_hex(0.945, n * 0.8, h),
    }
    bgs = [p["bg"], p["surface"], p["surface-2"]]
    p["muted"] = reach(6.0, bgs, 0.74, n * 1.6, h, darker=False)
    p["faint"] = reach(4.6, bgs, 0.64, n * 1.6, h, darker=False)
    soft = oklch_hex(0.29, c * 0.42, h)
    p["accent"] = reach(6.2, bgs + [soft], 0.72, c, h, darker=False)
    p["accent-hover"] = reach(contrast(p["accent"], p["surface"]) + 1.2, [p["surface"]], 0.78, c, h, darker=False)
    p["accent-ink"] = ink_for(p["accent"], h, 0.17)
    p["accent-soft"] = soft
    p["accent-line"] = oklch_hex(0.42, c * 0.6, h)
    for name, hue in (("ok", OK_H), ("warn", WARN_H), ("err", ERR_H), ("info", INFO_H)):
        tint = oklch_hex(0.27, 0.045, hue)
        p[f"{name}-soft"] = tint
        p[name] = reach(5.2, bgs + [tint], 0.72, 0.14, hue, darker=False)
    p["focus"] = p["accent"]
    p["chart-1"] = reach(3.0, [p["surface"]], 0.64, max(c, 0.13), h, darker=False)   # inside the dark chart band L 0.48-0.67
    p["chart-2"] = reach(3.0, [p["surface"]], 0.64, 0.12, h2, darker=False)
    p["chart-3"] = reach(3.0, [p["surface"]], 0.65, 0.13, (h + 90) % 360, darker=False)
    p["chart-4"] = p["faint"]
    return p


CHECKS = [  # foreground, background, minimum
    ("text", "bg", 7.0), ("text", "surface", 7.0), ("text", "surface-2", 7.0), ("text", "user", 7.0),
    ("muted", "bg", 4.5), ("muted", "surface", 4.5), ("muted", "surface-2", 4.5),
    ("faint", "surface", 4.5), ("faint", "surface-2", 4.5),
    ("accent", "surface", 4.5), ("accent", "bg", 4.5), ("accent", "accent-soft", 4.5),
    ("accent-ink", "accent", 4.5), ("accent-ink", "accent-hover", 4.5),
    ("ok", "surface", 4.5), ("ok", "ok-soft", 4.5), ("warn", "surface", 4.5), ("warn", "warn-soft", 4.5),
    ("err", "surface", 4.5), ("err", "err-soft", 4.5), ("info", "surface", 4.5),
    ("line-strong", "surface", 1.4),
]


def check(name: str, mode: str, p: dict[str, str]) -> list[str]:
    bad = []
    for fg, bg, need in CHECKS:
        ratio = contrast(p[fg], p[bg])
        if ratio < need:
            bad.append(f"{name}/{mode}: {fg} on {bg} = {ratio:.2f} (< {need})")
    return bad


def block(selector: str, p: dict[str, str], scheme: str, indent: str = "") -> str:
    shadow = ("0 1px 2px rgb(0 0 0 / 28%)", "0 8px 24px rgb(0 0 0 / 34%)", "0 18px 48px rgb(0 0 0 / 52%)") if scheme == "dark" else (
        "0 1px 2px rgb(20 20 15 / 7%)", "0 8px 24px rgb(20 20 15 / 8%)", "0 18px 48px rgb(20 20 15 / 16%)")
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  --{k}: {v};" for k, v in p.items()]
    lines += [f"{indent}  --shadow-sm: {shadow[0]};", f"{indent}  --shadow-md: {shadow[1]};", f"{indent}  --shadow-lg: {shadow[2]};",
              f"{indent}  color-scheme: {scheme};", f"{indent}}}"]
    return "\n".join(lines)


def build() -> tuple[str, list[str], list[str]]:
    parts, problems, table, swatches = [], [], [], []
    ids = " ".join(pid for pid, *_ in PALETTES)
    labels = " ".join(f"{pid}:{label}" for pid, label, *_ in PALETTES)
    parts.append(f':root {{ --palette-list: "{ids}"; --palette-labels: "{labels}"; }}')
    for i, (pid, label, h, c, n, h2) in enumerate(PALETTES):
        lp, dp = light(h, c, n, h2), dark(h, c, n, h2)
        problems += check(pid, "light", lp) + check(pid, "dark", dp)
        table.append(f"{label:<8} light: text {contrast(lp['text'], lp['bg']):5.2f}  muted {contrast(lp['muted'], lp['surface-2']):4.2f}  "
                     f"accent {contrast(lp['accent'], lp['surface']):4.2f}  ink {contrast(lp['accent-ink'], lp['accent']):4.2f} | "
                     f"dark: text {contrast(dp['text'], dp['bg']):5.2f}  muted {contrast(dp['muted'], dp['surface-2']):4.2f}  "
                     f"accent {contrast(dp['accent'], dp['surface']):4.2f}  ink {contrast(dp['accent-ink'], dp['accent']):4.2f}")
        sel = f':root[data-palette="{pid}"]'
        light_sel = f":root, {sel}" if i == 0 else sel
        dark_auto = ':root:not([data-theme="light"])' + (f', :root:not([data-theme="light"])[data-palette="{pid}"]' if i == 0
                                                          else f'[data-palette="{pid}"]')
        dark_forced = ':root[data-theme="dark"]' + (f', :root[data-theme="dark"][data-palette="{pid}"]' if i == 0 else f'[data-palette="{pid}"]')
        parts.append(f"/* {label}: hue {h}, accent chroma {c} */")
        parts.append(block(light_sel, lp, "light"))
        parts.append("@media (prefers-color-scheme: dark) {\n" + block(dark_auto, dp, "dark", "  ") + "\n}")
        parts.append(block(dark_forced, dp, "dark"))
        swatches.append(f'.sq-swatch[data-palette="{pid}"] {{ --sw-1: {lp["accent"]}; --sw-2: {lp["accent-soft"]}; '
                        f'--sw-3: {dp["surface"]}; --sw-4: {dp["accent"]}; }}')
    parts += swatches
    return "\n".join(parts), problems, table


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="print the contrast table, write nothing")
    a = ap.parse_args()
    css, problems, table = build()
    print("\n".join(table))
    if problems:
        print("\n".join(problems), file=sys.stderr)
        raise SystemExit(1)
    if a.check:
        return
    text = TOKENS.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"markers not found in {TOKENS}")
    TOKENS.write_text(pattern.sub(lambda _: f"{START}\n{css}\n{END}", text), encoding="utf-8")
    print(f"wrote {len(PALETTES)} palettes to {TOKENS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
