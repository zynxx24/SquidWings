"""Keep Codex's copy of the agent settings in step with Claude Code's.

One source: CLAUDE.md (which imports .claude/rules/*.md with ``@path`` lines) and .claude/skills/.
Generated from it, so the same rule is never written twice by hand:

* AGENTS.md: CLAUDE.md with every import written out, for Codex;
* .codex/skills/: a mirror of .claude/skills/;
* brain/system_prompt/_rules.txt: the ``<!-- prompt: ... -->`` line of each rule, for the models the harness runs;
* skills/builtin/bar-kualitas.md: the harness copy of the quality-gate skill;
* with ``--global``: the rules section of ~/.codex/AGENTS.md (below its marker; the owner's own text above it stays).

Usage:
    .venv/bin/python scripts/sync_agent_config.py            # write the generated files
    .venv/bin/python scripts/sync_agent_config.py --check    # exit 1 if they are out of date
    .venv/bin/python scripts/sync_agent_config.py --global   # also refresh ~/.codex/AGENTS.md
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "CLAUDE.md"
AGENTS = ROOT / "AGENTS.md"
CLAUDE_SKILLS = ROOT / ".claude" / "skills"
CODEX_SKILLS = ROOT / ".codex" / "skills"
RULES = ROOT / ".claude" / "rules"
PROMPT_RULES = ROOT / "brain" / "system_prompt" / "_rules.txt"
QUALITY_SOURCE = CLAUDE_SKILLS / "quality-gate" / "SKILL.md"
QUALITY_HARNESS = ROOT / "skills" / "builtin" / "bar-kualitas.md"
QUALITY_HEADER = """---
name: bar-kualitas
description: Bar kualitas wajib untuk setiap aplikasi, web, API, atau proyek - keamanan, kualitas kode, keandalan, performa, maintainability, dan usability semuanya harus lolos, dibuktikan PASS atau FAIL sebelum bilang selesai.
tasks: code, activity
triggers: aplikasi, app, web, website, api, backend, frontend, project, proyek, sistem, dashboard, admin panel, laravel, react, next, vue, express, fastapi, django, keamanan, security, celah, performa, performance, kualitas kode, code quality
scope: contextual
context: aplikasi, web, website, api, backend, frontend, proyek, project, sistem, deploy, produksi, production
companion: build-web, build-backend, add-feature, fix-bug, laravel
---
<!-- Generated from .claude/skills/quality-gate/SKILL.md by scripts/sync_agent_config.py. Edit that file. -->
"""
GLOBAL_CODEX = Path.home() / ".codex" / "AGENTS.md"
GLOBAL_MARKER = "<!-- squidwings rules: generated by ~/Documents/agent/scripts/sync_agent_config.py --global -->"
SUMMARY = re.compile(r"^<!-- prompt: (.+?) -->\s*$", re.MULTILINE)
IMPORT = re.compile(r"^@(\S+\.md)\s*$")
HEADER = ("<!-- Generated from CLAUDE.md and .claude/rules/ by scripts/sync_agent_config.py. "
          "Edit those files, not this one. -->\n\n")


def expand(text: str, base: Path, seen: frozenset[Path] = frozenset()) -> str:
    """CLAUDE.md with each ``@path`` import line replaced by the file it names (nested imports too)."""
    out: list[str] = []
    for line in text.splitlines():
        match = IMPORT.match(line)
        if not match:
            out.append(line)
            continue
        target = (base / match.group(1)).resolve()
        if target in seen:
            raise SystemExit(f"import cycle at {match.group(1)}")
        if not target.is_file() or ROOT not in target.parents:
            raise SystemExit(f"import not found inside the repo: {match.group(1)}")
        body = target.read_text(encoding="utf-8").strip()
        out.append(expand(body, target.parent, seen | {target}))
    return "\n".join(out)


def agents_text() -> str:
    return HEADER + expand(SOURCE.read_text(encoding="utf-8"), ROOT).rstrip() + "\n"


def rule_files() -> list[Path]:
    """The rules in the order CLAUDE.md imports them."""
    claude = SOURCE.read_text(encoding="utf-8")
    found = [(ROOT / m).resolve() for m in re.findall(IMPORT.pattern, claude, re.MULTILINE)
             if (ROOT / m).resolve().parent == RULES.resolve()]
    if not found:
        raise SystemExit("CLAUDE.md imports no rule from .claude/rules/")
    return found


def prompt_rules_text() -> str:
    lines = []
    for path in rule_files():
        match = SUMMARY.search(path.read_text(encoding="utf-8"))
        if not match:
            raise SystemExit(f"{path.name} has no <!-- prompt: ... --> line")
        lines.append(f"- {match.group(1).strip()}")
    return ("Working rules (from .claude/rules/; generated by scripts/sync_agent_config.py):\n" + "\n".join(lines) + "\n")


def quality_text() -> str:
    body = QUALITY_SOURCE.read_text(encoding="utf-8").split("---", 2)[2].lstrip("\n")
    return QUALITY_HEADER + body


def global_codex_text(current: str) -> str:
    """The owner's own text above the marker, the rules (written out) below it."""
    head = current.split(GLOBAL_MARKER, 1)[0].rstrip() if current else "# Global Codex instructions"
    # Lines other tools add for themselves (rtk's "@~/.codex/RTK.md") may land below the marker: keep them above it.
    for line in (current or "").splitlines():
        if re.fullmatch(r"@\S*RTK\.md\s*", line.strip()) and line.strip() not in head:
            head = f"{head}\n\n{line.strip()}"
    rules = "\n\n".join(p.read_text(encoding="utf-8").strip() for p in rule_files())
    return f"{head}\n\n{GLOBAL_MARKER}\n\n{SUMMARY.sub('', rules).strip()}\n"


def skill_files(folder: Path) -> dict[str, bytes]:
    if not folder.is_dir():
        return {}
    return {p.relative_to(folder).as_posix(): p.read_bytes() for p in sorted(folder.rglob("*")) if p.is_file()}


def differences() -> list[str]:
    found: list[str] = []
    if not AGENTS.is_file() or AGENTS.read_text(encoding="utf-8") != agents_text():
        found.append("AGENTS.md")
    if skill_files(CLAUDE_SKILLS) != skill_files(CODEX_SKILLS):
        found.append(".codex/skills/")
    if not PROMPT_RULES.is_file() or PROMPT_RULES.read_text(encoding="utf-8") != prompt_rules_text():
        found.append("brain/system_prompt/_rules.txt")
    if not QUALITY_HARNESS.is_file() or QUALITY_HARNESS.read_text(encoding="utf-8") != quality_text():
        found.append("skills/builtin/bar-kualitas.md")
    return found


def write(global_files: bool = False) -> None:
    AGENTS.write_text(agents_text(), encoding="utf-8")
    PROMPT_RULES.write_text(prompt_rules_text(), encoding="utf-8")
    QUALITY_HARNESS.write_text(quality_text(), encoding="utf-8")
    if global_files:
        current = GLOBAL_CODEX.read_text(encoding="utf-8") if GLOBAL_CODEX.is_file() else ""
        GLOBAL_CODEX.parent.mkdir(parents=True, exist_ok=True)
        GLOBAL_CODEX.write_text(global_codex_text(current), encoding="utf-8")
    if CODEX_SKILLS.exists():
        shutil.rmtree(CODEX_SKILLS)
    if CLAUDE_SKILLS.is_dir():
        shutil.copytree(CLAUDE_SKILLS, CODEX_SKILLS)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report whether the generated files are current")
    parser.add_argument("--global", dest="global_files", action="store_true", help="also refresh ~/.codex/AGENTS.md")
    args = parser.parse_args()
    if args.check:
        stale = differences()
        if stale:
            print("out of date: " + ", ".join(stale) + " (run scripts/sync_agent_config.py)")
            return 1
        print("agent config in sync")
        return 0
    write(args.global_files)
    print("wrote AGENTS.md, .codex/skills/, _rules.txt, bar-kualitas.md" + (" and ~/.codex/AGENTS.md" if args.global_files else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
